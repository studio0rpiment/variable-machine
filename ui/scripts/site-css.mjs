// The website's copy of the Start map needs the map's and the flags' styles, not the whole app's
// (which locks the page to the window). This pulls those rules out of src/styles.css on every
// site build, so the two never drift apart. Run by `npm run build:site`.
import fs from 'node:fs'

const src = fs.readFileSync(new URL('../src/styles.css', import.meta.url), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '')
const KEEP = /\.(flag|flow|is-explained|text-button|label|nav-step)(?![a-z])|@keyframes (flag-in|echo-in)/

// Split into top-level blocks by counting braces.
const blocks = []
let depth = 0
let start = 0
for (let i = 0; i < src.length; i++) {
  if (src[i] === '{') depth++
  else if (src[i] === '}' && --depth === 0) {
    blocks.push(src.slice(start, i + 1).trim())
    start = i + 1
  }
}
const kept = blocks.filter((b) => {
  const head = b.slice(0, b.indexOf('{'))
  if (/^@media/.test(head)) return KEEP.test(b) && /\.(flag|flow)/.test(b)
  return KEEP.test(head)
})
const out = `/* Generated by scripts/site-css.mjs from src/styles.css: the Start map and its flags, for the website. Don't edit. */\n${kept.join('\n')}\n`
fs.writeFileSync(new URL('../src/site/map.generated.css', import.meta.url), out)
console.log(`site css: ${kept.length} rules`)
